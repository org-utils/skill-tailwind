#!/usr/bin/env node
// generate-token-types.mjs — OPTIONAL TypeScript codegen from a real @theme block.
//
// The script is NOT required: the skill-tailwind skill works fully without it.
// No dependencies — only built-in Node modules (node:fs, node:path).
// Works offline, cross-platform (Windows/Unix), runnable via `node` or `bun`.
//
// What it does: parses the FIRST top-level `@theme { ... }` block in the given CSS file
// (default: templates/theme.css) and emits a `.d.ts` with literal-union types for the
// project's ACTUAL token names — not a guessed/hardcoded list. Re-run it whenever the
// project's own theme.css changes; the output always reflects the real tokens on disk.
//
// This intentionally does NOT try to type every Tailwind utility (the full utility
// namespace is enormous and versioned by Tailwind itself, not by this skill). It types
// only the project-specific axis — token names — which is the part IDE autocomplete and
// build-time typo detection actually need help with.
//
// Usage:
//   node scripts/generate-token-types.mjs [theme.css] [-o output.d.ts]
//   (defaults: templates/theme.css -> stdout)

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

function extractThemeVars(text) {
  const start = /@theme\s*\{/.exec(text);
  if (!start) return new Map();
  let i = text.indexOf('{', start.index);
  let depth = 1;
  let j = i + 1;
  for (; j < text.length && depth > 0; j++) {
    if (text[j] === '{') depth++;
    else if (text[j] === '}') depth--;
  }
  const body = text.slice(i + 1, j - 1);
  const vars = new Map();
  for (const m of body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
    vars.set(m[1], m[2].trim());
  }
  return vars;
}

// Group vars by their @theme namespace (color, font, radius, spacing, ...) — see
// docs/design-tokens.md / references/tokens.md for the namespace list this mirrors.
function groupByNamespace(vars) {
  const groups = new Map();
  for (const name of vars.keys()) {
    const m = /^--([a-z]+)-(.+)$/.exec(name);
    if (!m) continue;
    const [, ns, rest] = m;
    if (!groups.has(ns)) groups.set(ns, []);
    groups.get(ns).push(rest);
  }
  return groups;
}

// Utility-class namespaces that consume a --color-* token, per references/tokens.md's
// documented usage (bg-*, text-*, border-*, ring-*, etc.). Kept intentionally short and
// reviewable — extend this list if the project's review docs document more.
const COLOR_UTILITY_PREFIXES = [
  'bg', 'text', 'border', 'ring', 'ring-offset', 'divide', 'outline',
  'fill', 'stroke', 'from', 'via', 'to', 'caret', 'accent', 'decoration', 'shadow',
];

function toPascal(name) {
  return name.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase());
}

function emit(vars) {
  const groups = groupByNamespace(vars);
  const lines = [];
  lines.push('// AUTO-GENERATED by scripts/generate-token-types.mjs — do not edit by hand.');
  lines.push('// Regenerate after any change to the source theme.css:');
  lines.push('//   node scripts/generate-token-types.mjs path/to/theme.css -o path/to/tokens.d.ts');
  lines.push('');

  const colorNames = (groups.get('color') ?? []).filter((n) => !n.endsWith('-foreground'));
  if (colorNames.length) {
    lines.push(`export type ColorToken =`);
    lines.push(colorNames.map((n) => `  | '${n}'`).join('\n'));
    lines.push('');
  }

  for (const [ns, names] of groups) {
    if (ns === 'color') continue; // handled above (ColorToken, minus -foreground siblings)
    const typeName = `${toPascal(ns)}Token`;
    lines.push(`export type ${typeName} =`);
    lines.push([...new Set(names)].map((n) => `  | '${n}'`).join('\n'));
    lines.push('');
  }

  if (colorNames.length) {
    lines.push('// Utility-class literal types for every color-token-consuming namespace');
    lines.push('// (references/tokens.md). Narrower than the full Tailwind utility surface —');
    lines.push('// this only types the project-specific token axis, not Tailwind itself.');
    lines.push('export type ColorUtilityClass =');
    lines.push(
      COLOR_UTILITY_PREFIXES.map((p) => `  | \`${p}-\${ColorToken}\``).join('\n')
    );
    lines.push('');
    lines.push('/**');
    lines.push(' * Type-checked class-name joiner: accepts any known ColorUtilityClass plus');
    lines.push(' * arbitrary strings (so it never rejects non-color utilities) — a typo in a');
    lines.push(' * color-token utility fails to typecheck, everything else passes through.');
    lines.push(' */');
    lines.push('export function cn(...classes: (ColorUtilityClass | (string & {}))[]): string {');
    lines.push('  return classes.filter(Boolean).join(\' \');');
    lines.push('}');
  }

  return lines.join('\n') + '\n';
}

function main() {
  const args = process.argv.slice(2);
  let outPath = null;
  const positional = [];
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '-o' || args[i] === '--out') {
      outPath = args[++i];
    } else {
      positional.push(args[i]);
    }
  }
  const themePath = resolve(positional[0] ?? 'templates/theme.css');

  let text;
  try {
    text = readFileSync(themePath, 'utf8');
  } catch (err) {
    console.error(`generate-token-types: cannot read ${themePath}: ${err.message}`);
    process.exit(2);
  }

  const vars = extractThemeVars(text);
  if (vars.size === 0) {
    console.error(`generate-token-types: no @theme block found in ${themePath}`);
    process.exit(1);
  }

  const output = emit(vars);
  if (outPath) {
    writeFileSync(resolve(outPath), output, 'utf8');
    console.log(`generate-token-types: wrote ${vars.size} token(s) from ${themePath} to ${outPath}`);
  } else {
    process.stdout.write(output);
  }
}

main();
